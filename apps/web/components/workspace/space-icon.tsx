export function SpaceIcon({
  space,
  className,
}: {
  space: SpaceAppearance
  className?: string
}) {
  const Icon = space.iconName ? (icons[space.iconName] ?? Folder) : Folder
  return (
    <Icon
      aria-hidden="true"
      className={cn("shrink-0", className)}
      color={space.iconName ? (space.iconColor ?? undefined) : undefined}
    />
  )
}
